    /**
     * 判断文本是否含繁体特征字符
     */
    fun isTraditional(text: String): Boolean {
        return text.any { it in t2s }
    }

    /**
     * 繁转简。非繁体字符原样保留。
     */
    fun convert(text: String): String {
        if (!isTraditional(text)) return text
        return buildString(text.length) {
            for (ch in text) {
                append(t2s[ch] ?: ch)
            }
        }
    }

    /**
     * 繁转简后返回新的 LyricLine 列表
     */
    fun convertLines(lines: List<com.carlyrics.model.LyricLine>): List<com.carlyrics.model.LyricLine> {
        var anyConverted = false
        val converted = lines.map { line ->
            val t = convert(line.text)
            if (t != line.text) anyConverted = true
            line.copy(text = t)
        }
        return if (anyConverted) converted else lines
    }
